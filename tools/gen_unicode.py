"""generate src/unicode_tables.h: code point ranges for \\p{L}, \\p{N}, \\s (White_Space) and Python str.isdigit()
(used by the GPT-2 byte-level pre-tokenizer regex and the word flags). python3 tools/gen_unicode.py > src/unicode_tables.h"""
import sys, unicodedata

WS = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000}


def ranges(pred):
    out, a = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and a is None:
            a = cp
        if not ok and a is not None:
            out.append((a, cp - 1)); a = None
    if a is not None:
        out.append((a, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"static const uint32_t {name}[][2] = {{")
    for i in range(0, len(rs), 6):
        print("  " + " ".join(f"{{0x{a:X},0x{b:X}}}," for a, b in rs[i:i + 6]))
    print("};")


print(f"/* generated by tools/gen_unicode.py (Python unicodedata {unicodedata.unidata_version}); do not edit */")
print("#pragma once\n#include <stdint.h>")
emit("UT_LETTER", ranges(lambda c: unicodedata.category(chr(c)).startswith("L")))
emit("UT_NUMBER", ranges(lambda c: unicodedata.category(chr(c)).startswith("N")))
emit("UT_SPACE", ranges(lambda c: c in WS))
emit("UT_DIGIT", ranges(lambda c: chr(c).isdigit()))
